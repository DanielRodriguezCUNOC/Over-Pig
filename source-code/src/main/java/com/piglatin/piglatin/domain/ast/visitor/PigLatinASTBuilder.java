    public ASTNode visitBooleanOrExpression(LatinParser.BooleanOrExpressionContext ctx) {
        List<LatinParser.BooleanAndExpressionContext> operands = ctx.booleanAndExpression();
        ASTNode left = visit(operands.get(0));
        for (int i = 1; i < operands.size(); i++) {
            ASTNode right = visit(operands.get(i));
            left = new NodeBinaryOperation(
                    left,
                    "||",
                    right,
                    ctx.getStart().getLine(),
                    ctx.getStart().getCharPositionInLine());
        }
        return left;
    }

